/**
 * make-dev-harness.js - builds the panel's desktop harness from the panel itself
 *
 *   node tools/make-dev-harness.js           write dev-harness.html
 *   node tools/make-dev-harness.js --check   exit 1 when dev-harness.html is not what index.html makes
 *
 * dev-harness.html is index.html with three parts of dev-harness-parts.html put in:
 * HEAD before </head> (the harness chrome's style and the mock C++ bridge, which
 * has to come before every module script), BODY-TOP after <body> (toolbar, the
 * simulated game background) and BODY-END before </body> (the C++ call log, the
 * toolbar wiring). So the harness loads exactly the panel's markup and scripts,
 * in the panel's order; it drifted by 56 scripts when it was kept by hand.
 * run-tests.js runs the check. Plain Node, no packages.
 */
var fs = require('fs');
var path = require('path');

var PANEL = path.resolve(__dirname, '..', 'PrismaUI', 'views', 'SpellLearning', 'SpellLearningPanel');

function parts(text) {
    var result = {};
    var names = ['HEAD', 'BODY-TOP', 'BODY-END', 'END'];
    for (var i = 0; i < names.length - 1; i++) {
        var start = text.indexOf('<!--' + names[i] + '-->');
        var end = text.indexOf('<!--' + names[i + 1] + '-->');
        if (start < 0 || end < 0) throw new Error('dev-harness-parts.html has no ' + names[i] + ' part');
        result[names[i]] = text.slice(start + names[i].length + 7, end).replace(/^\r?\n/, '');
    }
    return result;
}

function insertAt(html, marker, text, after) {
    var at = html.indexOf(marker);
    if (at < 0) throw new Error('index.html has no ' + marker);
    var cut = after ? at + marker.length : at;
    var lead = after ? '\n' : '';
    return html.slice(0, cut) + lead + text + html.slice(cut);
}

function make() {
    var index = fs.readFileSync(path.join(PANEL, 'index.html'), 'utf8');
    var p = parts(fs.readFileSync(path.join(PANEL, 'dev-harness-parts.html'), 'utf8'));
    var html = index;
    html = insertAt(html, '</head>', p.HEAD, false);
    html = insertAt(html, '<body>', p['BODY-TOP'], true);
    html = insertAt(html, '</body>', p['BODY-END'], false);
    return html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by tools/make-dev-harness.js from index.html and dev-harness-parts.html - do not edit -->');
}

var TARGET = path.join(PANEL, 'dev-harness.html');

/** Is dev-harness.html what index.html makes now? (line endings aside) */
function isCurrent() {
    var current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
    return current.replace(/\r\n/g, '\n') === make().replace(/\r\n/g, '\n');
}

module.exports = { make: make, isCurrent: isCurrent, PANEL: PANEL };

if (require.main === module) {
    if (process.argv.indexOf('--check') >= 0) {
        if (!isCurrent()) {
            console.error('dev-harness.html is out of date: run node tools/make-dev-harness.js');
            process.exit(1);
        }
        console.log('dev-harness.html matches index.html');
    } else {
        fs.writeFileSync(TARGET, make());
        console.log('Wrote ' + TARGET);
    }
}
